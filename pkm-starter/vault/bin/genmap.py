#!/usr/bin/env python3
"""Generate MAP.md: a Mermaid dependency graph + reachability analysis from system frontmatter.

Answers 'how does this environment fit together' without holding it all in your head.
Renders natively on GitHub.
"""
import os, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from reindex import parse_frontmatter, ROOT  # noqa: E402

SYSDIR = os.path.join(ROOT, "systems")


def load():
    systems = {}
    for fn in sorted(os.listdir(SYSDIR)) if os.path.isdir(SYSDIR) else []:
        if not fn.endswith(".md") or fn == "README.md":
            continue
        meta = parse_frontmatter(os.path.join(SYSDIR, fn))
        if meta is None:
            continue
        slug = fn[:-3]
        meta["_slug"] = slug
        systems[slug] = meta
    return systems


def listify(meta, key):
    v = meta.get(key, [])
    if isinstance(v, str):
        v = [x.strip() for x in v.split(",") if x.strip()] if v else []
    return [x for x in v if x]


def main():
    systems = load()
    if not systems:
        print("no system profiles yet — create one with: bin/pkm new system <slug> \"<name>\"")
        return 0

    edges = set()
    referenced = set()
    for slug, m in systems.items():
        for dep in listify(m, "depends_on"):
            edges.add((dep, slug))
            referenced.add(dep)
        for down in listify(m, "used_by"):
            edges.add((slug, down))
            referenced.add(down)

    ghosts = sorted(referenced - set(systems))          # named as a dependency, no profile
    tiers = {s: m.get("tier", "") for s, m in systems.items()}

    out = [
        "<!-- GENERATED by bin/pkm map — do not hand-edit. -->",
        "# Environment map",
        "",
        "Arrows point **from a dependency to the thing that needs it**: `A --> B` means",
        "*B breaks when A breaks*. Trace downstream to answer \"what does this take out?\";",
        "trace upstream to answer \"what could be causing this?\".",
        "",
        "```mermaid",
        "graph LR",
    ]

    for slug, m in sorted(systems.items()):
        label = m.get("title", slug).replace('"', "'")
        crit = " ⚠️" if str(m.get("tier", "")).lower() in ("1", "critical", "p1") else ""
        shape = f'{slug}["{label}{crit}"]'
        out.append(f"  {shape}")
    for g in ghosts:
        out.append(f'  {g}[["{g}<br/>(no profile)"]]:::ghost')
    for a, b in sorted(edges):
        out.append(f"  {a} --> {b}")
    out.extend([
        "  classDef ghost fill:#fee,stroke:#c66,stroke-dasharray: 4 3;",
        "```",
        "",
    ])

    # Blast radius: transitive downstream closure
    down = collections.defaultdict(set)
    for a, b in edges:
        down[a].add(b)

    def closure(start):
        seen, stack = set(), [start]
        while stack:
            cur = stack.pop()
            for nxt in down.get(cur, ()):
                if nxt not in seen:
                    seen.add(nxt)
                    stack.append(nxt)
        return seen

    out.extend(["## Blast radius — if X fails, what else does", "",
                "| System | Directly breaks | Total downstream |",
                "|--------|-----------------|------------------|"])
    rows = []
    for slug in sorted(set(systems) | set(ghosts)):
        direct = sorted(down.get(slug, ()))
        total = closure(slug)
        rows.append((len(total), slug, direct, total))
    for n, slug, direct, total in sorted(rows, reverse=True):
        if not total:
            continue
        out.append(f"| `{slug}` | {', '.join(f'`{d}`' for d in direct)} | **{n}** — "
                   f"{', '.join(f'`{t}`' for t in sorted(total))} |")
    if not any(r[0] for r in rows):
        out.append("| _no dependencies recorded yet_ | | |")

    # Single points of failure
    spof = sorted((s for s in set(systems) | set(ghosts) if len(closure(s)) >= 2),
                  key=lambda s: -len(closure(s)))
    out.extend(["", "## Single points of failure (≥2 downstream)", ""])
    out.extend([f"- `{s}` → {len(closure(s))} systems" for s in spof] or ["_none recorded_"])

    leaves = sorted(s for s in systems if not listify(systems[s], "depends_on"))
    out.extend(["", "## No recorded upstream dependencies", "",
                "_Either genuinely standalone, or the profile is incomplete — usually the latter._", ""])
    out.extend([f"- `{s}`" for s in leaves] or ["_none_"])

    if ghosts:
        out.extend(["", "## ⚠️ Named as a dependency but has no profile", "",
                    "_These are blind spots: something you support depends on them and you have no notes._", ""])
        out.extend(f"- `{g}` — `bin/pkm new system {g} \"...\"`" for g in ghosts)

    with open(os.path.join(ROOT, "MAP.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"MAP.md: {len(systems)} systems, {len(edges)} dependencies, "
          f"{len(spof)} SPOFs, {len(ghosts)} undocumented")
    return 0


if __name__ == "__main__":
    sys.exit(main())
