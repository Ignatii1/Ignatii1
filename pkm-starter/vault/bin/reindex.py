#!/usr/bin/env python3
"""Regenerate INDEX.md from note frontmatter. No third-party deps by design."""
import os, re, sys, datetime, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = ["systems", "runbooks", "incidents", "references", "decisions", "contacts"]
STALE_DAYS = 180
TODAY = datetime.date.today()


def parse_frontmatter(path):
    """Minimal YAML-frontmatter reader: scalars and inline [a, b] lists."""
    try:
        with open(path, encoding="utf-8") as fh:
            if fh.readline().strip() != "---":
                return None
            body = []
            for line in fh:
                if line.strip() == "---":
                    break
                body.append(line)
            else:
                return None
    except (OSError, UnicodeDecodeError):
        return None

    meta = {}
    for line in body:
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", line.rstrip())
        if not m:
            continue
        key, raw = m.group(1), m.group(2).strip()
        if raw.startswith("[") and raw.endswith("]"):
            inner = raw[1:-1].strip()
            meta[key] = [v.strip().strip("'\"") for v in inner.split(",") if v.strip()]
        else:
            meta[key] = raw.strip("'\"")
    return meta


def collect():
    notes = []
    for d in DIRS:
        full = os.path.join(ROOT, d)
        if not os.path.isdir(full):
            continue
        for dirpath, _, files in os.walk(full):
            for fn in sorted(files):
                if not fn.endswith(".md") or fn == "README.md":
                    continue
                p = os.path.join(dirpath, fn)
                meta = parse_frontmatter(p)
                if meta is None:
                    continue
                meta["_path"] = os.path.relpath(p, ROOT)
                meta["_dir"] = d
                notes.append(meta)
    return notes


def age_days(meta):
    raw = meta.get("updated") or meta.get("created") or ""
    try:
        return (TODAY - datetime.date.fromisoformat(raw)).days
    except ValueError:
        return None


def systems_of(meta):
    v = meta.get("systems", [])
    return v if isinstance(v, list) else [v]


def main():
    notes = collect()
    by_type = collections.defaultdict(list)
    for n in notes:
        by_type[n.get("type", n["_dir"])].append(n)

    per_system = collections.defaultdict(lambda: collections.defaultdict(list))
    for n in notes:
        for s in systems_of(n):
            per_system[s][n.get("type", "other")].append(n)

    out = [
        "<!-- GENERATED by bin/pkm index — do not hand-edit. -->",
        f"# Vault Index",
        "",
        f"_{len(notes)} notes · rebuilt {TODAY.isoformat()}_",
        "",
        "## Systems",
        "",
        "| System | Status | Runbooks | Incidents | Refs | Last touched |",
        "|--------|--------|----------|-----------|------|--------------|",
    ]

    sysnotes = {}
    for n in by_type.get("system", []):
        for s in systems_of(n) or [os.path.basename(n["_path"])[:-3]]:
            sysnotes[s] = n

    for s in sorted(per_system):
        bucket = per_system[s]
        prof = sysnotes.get(s)
        link = f"[{s}]({prof['_path']})" if prof else f"{s} ⚠️ *no profile*"
        status = prof.get("status", "—") if prof else "—"
        ages = [a for a in (age_days(x) for x in bucket.get("incident", []) + ([prof] if prof else [])) if a is not None]
        touched = f"{min(ages)}d ago" if ages else "—"
        out.append(
            f"| {link} | {status} | {len(bucket.get('runbook', []))} "
            f"| {len(bucket.get('incident', []))} | {len(bucket.get('reference', []))} | {touched} |"
        )

    def section(title, typ, limit=None, datekey="created"):
        items = sorted(by_type.get(typ, []), key=lambda x: x.get(datekey, ""), reverse=True)
        if limit:
            items = items[:limit]
        out.extend(["", f"## {title}", ""])
        if not items:
            out.append("_none yet_")
            return
        for n in items:
            sys_s = ", ".join(systems_of(n)) or "—"
            st = n.get("status", "")
            flag = " 🔴" if st == "open" else ""
            out.append(f"- [{n.get('title', n['_path'])}]({n['_path']}) — `{sys_s}` · {st}{flag}")

    section("Recent incidents", "incident", limit=25)
    section("Runbooks", "runbook")
    section("References", "reference")
    section("Decisions", "decision")

    open_items = [n for n in notes if n.get("status") == "open"]
    out.extend(["", "## Open items", ""])
    out.extend([f"- [{n.get('title')}]({n['_path']})" for n in open_items] or ["_none_"])

    stale = [(a, n) for n in notes if (a := age_days(n)) is not None and a > STALE_DAYS
             and n.get("type") in ("system", "runbook", "reference")]
    out.extend(["", f"## Stale (>{STALE_DAYS}d — verify before trusting)", ""])
    out.extend([f"- [{n.get('title')}]({n['_path']}) — {a}d" for a, n in sorted(stale, reverse=True)] or ["_none_"])

    orphans = [n for n in notes if not systems_of(n) and n.get("type") != "contact"]
    if orphans:
        out.extend(["", "## ⚠️ Unreachable (no `systems:` — will not be found)", ""])
        out.extend(f"- [{n.get('title', n['_path'])}]({n['_path']})" for n in orphans)

    with open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"INDEX.md: {len(notes)} notes, {len(per_system)} systems, "
          f"{len(open_items)} open, {len(stale)} stale, {len(orphans)} orphaned")


if __name__ == "__main__":
    sys.exit(main())
